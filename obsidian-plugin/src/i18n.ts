export const LOCALES: Record<Lang, Record<MessageKey, string>> = { zh, en };
/** The name of each language in that language (the language setting lists them). */
export const LANGUAGE_NAMES: Record<Lang, string> = { en: "English", zh: "中文" };
let currentLang: Lang = "zh";

export function setLocale(lang: Lang): void {
	currentLang = lang in LOCALES ? lang : "zh";
}

export function locale(): Lang {
	return currentLang;
}

export function t(key: MessageKey, vars: Record<string, string | number> = {}): string {
	return (LOCALES[currentLang][key] ?? key).replace(/\{(\w+)\}/g, (_, k: string) => (k in vars ? String(vars[k]) : `{${k}}`));
}

export function timeUnits() {
	return { min: t("time.min"), hour: t("time.hour"), day: t("time.day"), month: t("time.month"), year: t("time.year") };
}

export function ratingLabel(r: number): string {
	return r >= 1 && r <= 4 ? t(`rating.${r}` as MessageKey) : String(r);
}
