"""Where things live inside a vault (folder names are configuration).

Defaults match the original vault (``10_Knowledge``, ``20_MOCs`` ...). Each
module asks :func:`of` for the layout of the vault it works on. The CLI
registers the configured layout for the configured vault; tests and other
callers can :func:`register` one explicitly.
"""
from __future__ import annotations

import os
from dataclasses import dataclass, fields


def _clean(value: str, name: str) -> str:
    if not isinstance(value, str) or not value or value.startswith('/') or value.endswith('/'):
        raise ValueError(f'[layout] {name} must be a relative folder like "10_Knowledge"')
    parts = value.split('/')
    if any(p in {'', '.', '..', '.git'} for p in parts) or '\\' in value or '\x00' in value:
        raise ValueError(f'[layout] {name} is not a clean relative path: {value!r}')
    return value


@dataclass(frozen=True)
class VaultLayout:
    knowledge: str = '10_Knowledge'
    mocs: str = '20_MOCs'
    taxonomy: str = '20_MOCs/_pillars'
    sources: str = '40_Sources'
    inbox: str = '00_Inbox'
    reviews: str = '50_Reviews'
    data: str = '_data'
    #: Entry page regenerated by the daily projection.
    home: str = 'HOME.md'
    #: Hand-written top-level docs whose generated marker blocks `sb docs` refreshes
    #: (none by default; list them under ``[layout] entry_docs``).
    entry_docs: tuple = ()
    #: Additional top-level folders counted in HOME's folder table and the optional
    #: `kb-dirs` block (none by default; list them under ``[layout] extra_dirs``).
    extra_dirs: tuple = ()

    def __post_init__(self):
        for f in ('knowledge', 'mocs', 'taxonomy', 'sources', 'inbox', 'reviews', 'data'):
            _clean(getattr(self, f), f)
        for name in (self.home, *self.entry_docs):
            if not isinstance(name, str) or '/' in name or not name.endswith('.md'):
                raise ValueError(f'[layout] entry files must be top-level .md names: {name!r}')
        object.__setattr__(self, 'entry_docs', tuple(self.entry_docs))
        object.__setattr__(self, 'extra_dirs', tuple(self.extra_dirs))
        owned = [self.knowledge, self.mocs, self.sources, self.inbox, self.reviews, self.data]
        for i, a in enumerate(owned):
            for b in owned[i + 1:]:
                if a == b or a.startswith(b + '/') or b.startswith(a + '/'):
                    raise ValueError(f'[layout] folders overlap: {a!r} and {b!r}')

    # -- derived files ------------------------------------------------------
    @property
    def registry(self) -> str:
        return f'{self.data}/notes_registry.json'

    @property
    def catalog(self) -> str:
        return f'{self.data}/secondbrain/catalog.json'

    @property
    def manifest(self) -> str:
        return f'{self.data}/manifest.jsonl'

    @property
    def ingested(self) -> str:
        return f'{self.data}/ingested.jsonl'

    @property
    def inbox_registry(self) -> str:
        return f'{self.data}/secondbrain/inbox_registry.jsonl'

    @property
    def conflicts(self) -> str:
        """Disagreements between new and existing cards that ingest found and left to the owner."""
        return f'{self.data}/secondbrain/conflicts.jsonl'

    @property
    def review_events(self) -> str:
        return f'{self.data}/review_events.jsonl'

    @property
    def review_log_dir(self) -> str:
        """Append-only review event logs (docs/review-registry.md section 1)."""
        return f'{self.data}/review'

    @property
    def projections(self) -> str:
        return f'{self.data}/projections'

    @property
    def standalone_files(self) -> tuple:
        return (self.home, *self.entry_docs)

    @property
    def counted_dirs(self) -> list:
        # not the data folder: review logs land there between writes (the plugin, `sb review log`), so a count
        # written into HOME went stale at once (drill 3)
        tops = {p.split('/')[0] for p in (self.inbox, self.knowledge, self.mocs, self.sources, self.reviews)}
        return sorted(tops | set(self.extra_dirs))

    # -- path builders ------------------------------------------------------
    def card_path(self, domain: str, filename: str) -> str:
        return f'{self.knowledge}/{domain}/{filename}'

    def taxonomy_path(self, moc_title: str) -> str:
        return f'{self.taxonomy}/{moc_title}.yaml'

    def moc_page(self, *segments: str) -> str:
        return '/'.join([self.mocs, *segments])

    def source_path(self, sha256: str, filename: str) -> str:
        return f'{self.sources}/{sha256[:16]}/{filename}'

    # -- classifiers --------------------------------------------------------
    @staticmethod
    def _under(rel: str, folder: str) -> tuple | None:
        prefix = folder + '/'
        if not rel.startswith(prefix):
            return None
        return tuple(rel[len(prefix):].split('/'))

    def is_card(self, rel: str) -> bool:
        rest = self._under(rel, self.knowledge)
        return rest is not None and len(rest) == 2 and rest[1].endswith('.md')

    def card_domain(self, rel: str) -> str | None:
        rest = self._under(rel, self.knowledge)
        return rest[0] if rest is not None and len(rest) == 2 else None

    def is_taxonomy_file(self, rel: str) -> bool:
        rest = self._under(rel, self.taxonomy)
        return rest is not None and len(rest) == 1 and rest[0].endswith('.yaml')

    def is_moc_page(self, rel: str) -> bool:
        if self._under(rel, self.taxonomy) is not None:
            return False
        rest = self._under(rel, self.mocs)
        return rest is not None and 1 <= len(rest) <= 2 and rest[-1].endswith('.md')

    def is_source(self, rel: str) -> bool:
        rest = self._under(rel, self.sources)
        return rest is not None and len(rest) >= 2

    def is_inbox_file(self, rel: str) -> bool:
        rest = self._under(rel, self.inbox)
        return rest is not None and len(rest) == 1

    def is_review_page(self, rel: str) -> bool:
        rest = self._under(rel, self.reviews)
        return rest is not None and len(rest) == 1 and rest[0].endswith('.md')

    def is_projection_json(self, rel: str) -> bool:
        rest = self._under(rel, self.projections)
        return rest is not None and len(rest) == 1 and rest[0].endswith('.json')

    @classmethod
    def from_mapping(cls, data: dict) -> 'VaultLayout':
        known = {f.name for f in fields(cls)}
        unknown = sorted(set(data) - known)
        if unknown:
            raise ValueError(f'Unknown [layout] keys: {unknown}')
        values = dict(data)
        for key in ('entry_docs', 'extra_dirs'):
            if key in values:
                if not isinstance(values[key], list) or not all(isinstance(x, str) for x in values[key]):
                    raise ValueError(f'[layout] {key} must be a list of strings')
                values[key] = tuple(values[key])
        return cls(**values)


DEFAULT = VaultLayout()
_REGISTERED: dict[str, VaultLayout] = {}


def _key(root) -> str:
    return os.path.realpath(os.fspath(root))


def register(root, layout: VaultLayout) -> None:
    _REGISTERED[_key(root)] = layout


def unregister_all() -> None:
    _REGISTERED.clear()


def of(root) -> VaultLayout:
    """Layout for ``root``: registered, else the configured vault's, else default."""
    key = _key(root)
    if key in _REGISTERED:
        return _REGISTERED[key]
    from . import config
    settings = config.current()
    if settings.vault is not None and _key(settings.vault) == key:
        return settings.layout
    return DEFAULT
